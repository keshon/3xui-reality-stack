"""Literal dotenv I/O shared by Python, Bash and Compose.

Generated values are double quoted, with dollar signs escaped for Compose.
No shell evaluation or variable interpolation ever happens here.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
import re
import tempfile

KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def atomic_write(path: Path, text: str) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix="." + path.name + "-", dir=path.parent)
    try:
        if hasattr(os, "fchmod"):
            os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(name, path)
        if os.name != "nt":
            directory = os.open(path.parent, os.O_RDONLY)
            try:
                os.fsync(directory)
            finally:
                os.close(directory)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def parse_env(text: str) -> dict[str, str]:
    result = {}
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[7:].lstrip()
        key, sep, value = line.partition("=")
        key, value = key.strip(), value.strip()
        if not sep or not KEY.fullmatch(key) or key in result:
            raise ValueError(f".env line {number}: invalid or duplicate key")
        if value.startswith(('"', "'")):
            quote, chars, index = value[0], [], 1
            while index < len(value):
                char = value[index]
                if char == quote:
                    tail = value[index + 1:].strip()
                    if tail and not tail.startswith("#"):
                        raise ValueError(f".env line {number}: text after closing quote")
                    break
                if char == "\\" and index + 1 < len(value):
                    following = value[index + 1]
                    escapes = {'"': '"', "\\": "\\", "$": "$", "n": "\n", "r": "\r", "t": "\t"}
                    if quote == '"' and following in escapes:
                        chars.append(escapes[following])
                        index += 2
                        continue
                    if quote == "'" and following == "'":
                        chars.append("'")
                        index += 2
                        continue
                chars.append(char)
                index += 1
            else:
                raise ValueError(f".env line {number}: unclosed quote")
            value = "".join(chars)
        else:
            value = value.split(" #", 1)[0].rstrip()
        if any(ord(c) < 32 or ord(c) == 127 for c in value):
            raise ValueError(f"{key}: control characters and multiline values are not supported")
        result[key] = value
    return result


def read_env(path: Path) -> dict[str, str]:
    path = Path(path)
    return parse_env(path.read_text(encoding="utf-8-sig")) if path.exists() else {}


def render_env(values: dict[str, str]) -> str:
    lines = ["# Generated by stack. Edit with: stack wizard"]
    for key, value in values.items():
        if not KEY.fullmatch(key) or not isinstance(value, str) or any(ord(c) < 32 or ord(c) == 127 for c in value):
            raise ValueError(f"{key}: invalid environment entry")
        lines.append(f"{key}=" + json.dumps(value, ensure_ascii=False).replace("$", "\\$"))
    return "\n".join(lines) + "\n"


def update_env(path: Path, values: dict[str, str]) -> None:
    current = read_env(path)
    current.update(values)
    atomic_write(path, render_env(current))
